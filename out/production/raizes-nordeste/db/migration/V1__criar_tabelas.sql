-- Esquema inicial (PostgreSQL). Corresponde às entidades JPA e ao diagrama ER.
-- Campos além do ER inicial: pedido.chave_idempotencia, pedido.pagamento_antecipado, pagamento.versao,
-- campanha.multiplicador, movimentacao_estoque.motivo e cliente.senha_hash.

CREATE TABLE unidade (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(120) NOT NULL,
    cidade                VARCHAR(80),
    regiao                VARCHAR(60),
    tipo_atendimento      VARCHAR(40),
    horario_funcionamento VARCHAR(120),
    ativa                 BOOLEAN NOT NULL
);

CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id  BIGINT REFERENCES unidade (id),
    nome        VARCHAR(120) NOT NULL,
    email       VARCHAR(160) NOT NULL UNIQUE,
    senha_hash  VARCHAR(100) NOT NULL,
    perfil      VARCHAR(20)  NOT NULL,
    ativo       BOOLEAN      NOT NULL
);

CREATE TABLE cliente (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(160) NOT NULL UNIQUE,
    telefone   VARCHAR(30),
    senha_hash VARCHAR(100) NOT NULL,
    criado_em  TIMESTAMP    NOT NULL
);

CREATE TABLE consentimento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id    BIGINT      NOT NULL REFERENCES cliente (id),
    finalidade    VARCHAR(60) NOT NULL,
    base_legal    VARCHAR(60) NOT NULL,
    concedido     BOOLEAN     NOT NULL,
    registrado_em TIMESTAMP   NOT NULL
);

CREATE TABLE produto (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120)   NOT NULL,
    descricao  VARCHAR(400),
    preco_base NUMERIC(12, 2) NOT NULL,
    sazonal    BOOLEAN        NOT NULL
);

CREATE TABLE cardapio_unidade (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id   BIGINT         NOT NULL REFERENCES unidade (id),
    produto_id   BIGINT         NOT NULL REFERENCES produto (id),
    preco        NUMERIC(12, 2) NOT NULL,
    habilitado   BOOLEAN        NOT NULL,
    inicio_venda DATE,
    fim_venda    DATE,
    CONSTRAINT uk_cardapio_unidade_produto UNIQUE (unidade_id, produto_id)
);

CREATE TABLE estoque (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT  NOT NULL REFERENCES unidade (id),
    produto_id BIGINT  NOT NULL REFERENCES produto (id),
    quantidade INTEGER NOT NULL,
    reservado  INTEGER NOT NULL,
    CONSTRAINT uk_estoque_unidade_produto UNIQUE (unidade_id, produto_id),
    CONSTRAINT ck_estoque_quantidade CHECK (quantidade >= 0),
    CONSTRAINT ck_estoque_reservado CHECK (reservado >= 0 AND reservado <= quantidade)
);

CREATE TABLE pedido (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id           BIGINT REFERENCES cliente (id),
    unidade_id           BIGINT         NOT NULL REFERENCES unidade (id),
    canal                VARCHAR(20)    NOT NULL,
    status               VARCHAR(30)    NOT NULL,
    pagamento_antecipado BOOLEAN        NOT NULL,
    valor_desconto       NUMERIC(12, 2) NOT NULL,
    valor_total          NUMERIC(12, 2) NOT NULL,
    criado_em            TIMESTAMP      NOT NULL,
    chave_idempotencia   VARCHAR(100),
    CONSTRAINT uk_pedido_chave_idempotencia UNIQUE (chave_idempotencia)
);

CREATE TABLE item_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT         NOT NULL REFERENCES pedido (id),
    produto_id     BIGINT         NOT NULL REFERENCES produto (id),
    quantidade     INTEGER        NOT NULL,
    preco_unitario NUMERIC(12, 2) NOT NULL
);

CREATE TABLE movimentacao_estoque (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estoque_id BIGINT      NOT NULL REFERENCES estoque (id),
    usuario_id BIGINT REFERENCES usuario (id),
    pedido_id  BIGINT REFERENCES pedido (id),
    tipo       VARCHAR(20) NOT NULL,
    quantidade INTEGER     NOT NULL,
    motivo     VARCHAR(200),
    data_hora  TIMESTAMP   NOT NULL
);

CREATE TABLE historico_status (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT      NOT NULL REFERENCES pedido (id),
    usuario_id      BIGINT REFERENCES usuario (id),
    status_anterior VARCHAR(30),
    status_novo     VARCHAR(30) NOT NULL,
    data_hora       TIMESTAMP   NOT NULL
);

CREATE TABLE pagamento (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id            BIGINT         NOT NULL REFERENCES pedido (id),
    provedor             VARCHAR(60)    NOT NULL,
    id_transacao_externo VARCHAR(80)    NOT NULL UNIQUE,
    status               VARCHAR(20)    NOT NULL,
    valor                NUMERIC(12, 2) NOT NULL,
    atualizado_em        TIMESTAMP      NOT NULL,
    versao               BIGINT         NOT NULL
);

CREATE TABLE registro_historico (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT      NOT NULL REFERENCES usuario (id),
    acao         VARCHAR(60) NOT NULL,
    entidade     VARCHAR(60) NOT NULL,
    entidade_id  BIGINT,
    dados_antes  TEXT,
    dados_depois TEXT,
    data_hora    TIMESTAMP   NOT NULL
);

CREATE TABLE campanha (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(120)  NOT NULL,
    regra         VARCHAR(300),
    multiplicador NUMERIC(5, 2) NOT NULL,
    inicio        DATE          NOT NULL,
    fim           DATE          NOT NULL,
    ativa         BOOLEAN       NOT NULL
);

CREATE TABLE movimento_pontos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  BIGINT      NOT NULL REFERENCES cliente (id),
    pedido_id   BIGINT REFERENCES pedido (id),
    campanha_id BIGINT REFERENCES campanha (id),
    pontos      INTEGER     NOT NULL,
    tipo        VARCHAR(20) NOT NULL,
    data_hora   TIMESTAMP   NOT NULL
);

-- Índices para as consultas mais frequentes
CREATE INDEX idx_pedido_unidade_status_criado ON pedido (unidade_id, status, criado_em);
CREATE INDEX idx_pedido_cliente ON pedido (cliente_id);
CREATE INDEX idx_item_pedido_pedido ON item_pedido (pedido_id);
CREATE INDEX idx_historico_status_pedido ON historico_status (pedido_id);
CREATE INDEX idx_movimentacao_estoque_estoque ON movimentacao_estoque (estoque_id, data_hora);
CREATE INDEX idx_pagamento_pedido ON pagamento (pedido_id);
CREATE INDEX idx_registro_historico_data ON registro_historico (data_hora);
CREATE INDEX idx_movimento_pontos_cliente ON movimento_pontos (cliente_id);
